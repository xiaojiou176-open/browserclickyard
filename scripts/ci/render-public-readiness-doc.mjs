#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import YAML from "../lib/yaml-loader.mjs";

const repoRoot = process.cwd();
const configPath = resolve(repoRoot, "configs/governance/public-readiness.yaml");
const outputPath = resolve(repoRoot, "docs/reference/public-readiness.md");
const checkOnly = process.argv.includes("--check");

const config = YAML.parse(readFileSync(configPath, "utf8"));

function renderList(items) {
  if (!Array.isArray(items) || items.length === 0) {
    return ["- _none_"];
  }
  return items.map((item) => `- ${item}`);
}

function renderPathList(items) {
  if (!Array.isArray(items) || items.length === 0) {
    return "_none_";
  }
  return items.map((entry) => `\`${entry}\``).join(", ");
}

function renderClaimRows(items) {
  if (!Array.isArray(items) || items.length === 0) {
    return ["| _none_ | _none_ | _none_ |"];
  }
  return items.map((item) => {
    return `| \`${item.id}\` | ${item.claim} | ${renderPathList(item.evidence)} |`;
  });
}

function renderAuditPathRows(items) {
  if (!Array.isArray(items) || items.length === 0) {
    return ["| _none_ | _none_ | _none_ | _none_ | _none_ |"];
  }
  return items.map((item) => {
    return `| \`${item.id}\` | ${item.surface} | \`${item.verification_mode}\` | ${renderPathList(item.paths)} | ${item.detail} |`;
  });
}

function renderRemoteRows(items) {
  if (!Array.isArray(items) || items.length === 0) {
    return ["| _none_ | _none_ | _none_ | _none_ | _none_ |"];
  }
  return items.map((item) => {
    return `| \`${item.id}\` | ${item.surface} | \`${item.status}\` | ${item.why} | ${renderPathList(item.reverify_paths)} |`;
  });
}

function renderStatusRows(items) {
  if (!Array.isArray(items) || items.length === 0) {
    return ["| _none_ | _none_ | _none_ | _none_ | _none_ | _none_ |"];
  }
  return items.map((item) => {
    return `| \`${item.id}\` | \`${item.class}\` | \`${item.status}\` | \`${item.owner}\` | ${item.summary} | ${renderPathList(item.evidence)} |`;
  });
}

const lines = [
  "# Reference: Public Readiness",
  "",
  "Generated from `configs/governance/public-readiness.yaml`. Do not edit this file manually.",
  "",
  "## Tracked Policy Mode",
  "",
  "| Key | Value |",
  "| --- | --- |",
  `| mode | \`${config.current_mode}\` |`,
  `| public claim allowed | \`${String(config.public_claim_allowed)}\` |`,
  `| english canonical status | \`${config.english_canonical_status}\` |`,
  `| artifact publication mode | \`${config.artifact_publication_mode}\` |`,
  "",
  "## Current Statement",
  "",
  `> ${config.current_statement}`,
  "",
  "## Repo-side Confirmed",
  "",
  "| ID | Claim | Evidence |",
  "| --- | --- | --- |",
  ...renderClaimRows(config.repo_side_confirmed),
  "",
  "## Repo-side Limitations",
  "",
  ...renderList(config.repo_side_limitations),
  "",
  "## Audit Paths That Exist",
  "",
  "| ID | Surface | Verification Mode | Paths | Detail |",
  "| --- | --- | --- | --- | --- |",
  ...renderAuditPathRows(config.audit_paths),
  "",
  "## Remote State Still Unknown Or Manual",
  "",
  "| ID | Remote Surface | Status | Why It Stays Out Of Tracked Truth | Reverify Path |",
  "| --- | --- | --- | --- | --- |",
  ...renderRemoteRows(config.remote_state_unknown_or_manual),
  "",
  "## External Blockers",
  "",
  "| ID | Class | Status | Owner | Detail | Evidence |",
  "| --- | --- | --- | --- | --- | --- |",
  ...renderStatusRows(config.external_blockers),
  "",
  "## Deferred Public-readiness Preconditions",
  "",
  "| ID | Class | Status | Owner | Detail | Evidence |",
  "| --- | --- | --- | --- | --- | --- |",
  ...renderStatusRows(config.deferred_preconditions),
  "",
  "## Interpretation",
  "",
  "- This page is a repo-side truth reference, not a completion announcement.",
  "- `repo-side confirmed` means the repository itself contains the tracked source, script, or workflow named in the evidence column.",
  "- `audit path exists` means the repository has a way to re-check a remote GitHub surface; it does not mean the current remote setting already passed that check.",
  "- `unknown` or `manual verification required` means tracked docs must stay honest and avoid restating live GitHub settings as fact until a fresh audit artifact or direct settings review confirms them.",
  "",
];

const rendered = `${lines.join("\n")}\n`;

if (checkOnly) {
  const current = readFileSync(outputPath, "utf8");
  if (current !== rendered) {
    console.error("[public-readiness-render] FAIL docs/reference/public-readiness.md is out of date");
    process.exit(1);
  }
  console.log("[public-readiness-render] PASS");
  process.exit(0);
}

writeFileSync(outputPath, rendered, "utf8");
console.log(`[public-readiness-render] WROTE ${outputPath}`);
