#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import YAML from "../lib/yaml-loader.mjs";

const THRESHOLD_KEYS = [
  "consoleErrorMax",
  "pageErrorMax",
  "http5xxMax",
  "contractStatus",
  "dangerousActionHitsMax",
  "securityHighVulnMax",
  "a11ySeriousMax",
  "perfLcpMsMax",
  "perfFcpMsMax",
  "visualDiffPixelsMax",
  "loadFailedRequestsMax",
  "loadP95MsMax",
  "loadRpsMin",
];

function parseArgs(argv) {
  const options = {
    configPath: "configs/governance/ci-governance.yaml",
    outputPath: "docs/reference/ci-governance.md",
    check: false,
    stdout: false,
  };

  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];
    const next = argv[index + 1];
    if (token === "--config" && next) {
      options.configPath = next;
      index += 1;
      continue;
    }
    if (token === "--output" && next) {
      options.outputPath = next;
      index += 1;
      continue;
    }
    if (token === "--check") {
      options.check = true;
      continue;
    }
    if (token === "--stdout") {
      options.stdout = true;
    }
  }

  return options;
}

function loadYaml(filePath) {
  return YAML.parse(readFileSync(resolve(filePath), "utf8"));
}

function getProfileThresholds(profileName) {
  const profile = loadYaml(`configs/profiles/${profileName}.yaml`);
  const gates = profile?.gates ?? {};
  const result = {};
  for (const key of THRESHOLD_KEYS) {
    result[key] = gates[key] ?? "n/a";
  }
  return result;
}

function renderList(items) {
  if (!Array.isArray(items) || items.length === 0) {
    return "_none_";
  }
  return items.map((item) => `\`${item}\``).join(", ");
}

function renderAggregateRows(config) {
  const rows = [];
  for (const scope of ["ci", "pr"]) {
    const aggregate = config.aggregates?.[scope];
    const requiredJobs = config.required_jobs?.[scope] ?? [];
    rows.push(
      `| ${scope} | \`${aggregate.workflow}\` | \`${aggregate.job}\` | ${requiredJobs.length} | ${renderList(requiredJobs)} |`,
    );
  }
  for (const scope of ["nightly"]) {
    const requiredJobs = config.required_jobs?.[scope] ?? [];
    const workflow = `.github/workflows/${scope}.yml`;
    rows.push(
      `| ${scope} | \`${workflow}\` | _single required job_ | ${requiredJobs.length} | ${renderList(requiredJobs)} |`,
    );
  }
  return rows;
}

function renderOptionalRows(config) {
  const rows = [];
  for (const scope of ["ci", "pr", "nightly"]) {
    const item = config.optional_jobs?.[scope];
    rows.push(
      `| ${scope} | \`${item?.workflow ?? "n/a"}\` | ${renderList(item?.jobs ?? [])} |`,
    );
  }
  return rows;
}

function renderManualDispatchRows(config) {
  const rows = [];
  for (const scope of ["nightly"]) {
    const item = config.manual_dispatch_jobs?.[scope];
    rows.push(
      `| ${scope} | \`${item?.workflow ?? `.github/workflows/${scope}.yml`}\` | ${renderList(item?.jobs ?? [])} |`,
    );
  }
  return rows.length > 0 ? rows : ["| _none_ | _none_ | _none_ |"];
}

function renderFeatureRows(config) {
  return Object.entries(config.features ?? {}).map(([featureName, feature]) => {
    return `| \`${featureName}\` | \`${feature.status}\` | \`${feature.workflow}\` | \`${feature.job}\` |`;
  });
}

function renderContinueOnErrorRows(config) {
  const rows = [];
  const workflowMap = config.policy_flags?.allowed_continue_on_error_steps ?? {};
  for (const [workflowPath, jobs] of Object.entries(workflowMap)) {
    for (const [jobName, stepNames] of Object.entries(jobs ?? {})) {
      rows.push(`| \`${workflowPath}\` | \`${jobName}\` | ${renderList(stepNames)} |`);
    }
  }
  return rows.length > 0 ? rows : ["| _none_ | _none_ | _none_ |"];
}

function renderDeterministicCoreRows(config) {
  const entrypoints = config.policy_flags?.deterministic_core_entrypoints ?? {};
  const rows = [];
  for (const scope of ["nightly"]) {
    rows.push(`| ${scope} | \`${entrypoints[scope] ?? "_none_"}\` |`);
  }
  return rows;
}

function renderThresholdRows(thresholdsByProfile) {
  return THRESHOLD_KEYS.map((key) => {
    return `| \`${key}\` | \`${thresholdsByProfile.pr[key]}\` | \`${thresholdsByProfile.nightly[key]}\` |`;
  });
}

function renderDoc(config, configPath) {
  const thresholdsByProfile = {
    pr: getProfileThresholds("pr"),
    nightly: getProfileThresholds("nightly"),
  };

  const lines = [];
  lines.push("# Reference: CI Governance");
  lines.push("");
  lines.push(`Generated from \`${configPath}\`. Do not edit this file manually.`);
  lines.push("");
  lines.push("This page is the render-only reference for current CI topology, required");
  lines.push("aggregate policy, disabled governance features, and generated threshold");
  lines.push("summary.");
  lines.push("");
  lines.push("Rendered from multiple tracked sources:");
  lines.push("");
  lines.push(`- Primary topology source: \`${configPath}\``);
  lines.push("- Threshold sources: `configs/profiles/pr.yaml`, `configs/profiles/nightly.yaml`");
  lines.push("- This page is a generated reference, not the canonical place to hand-edit CI facts.");
  lines.push("- Nightly required rows describe deterministic core only; live external, mutation, AI review, and other privileged observability checks stay in manual-only sections below.");
  lines.push("");
  lines.push("## Aggregate Checks");
  lines.push("");
  lines.push("| Scope | Workflow | Aggregate Job | Required Job Count | Required Jobs |");
  lines.push("| --- | --- | --- | ---: | --- |");
  lines.push(...renderAggregateRows(config));
  lines.push("");
  lines.push("## Optional Jobs");
  lines.push("");
  lines.push("| Scope | Workflow | Observational / Non-required Jobs |");
  lines.push("| --- | --- | --- |");
  lines.push(...renderOptionalRows(config));
  lines.push("");
  lines.push("## Manual Dispatch Jobs");
  lines.push("");
  lines.push("| Scope | Workflow | workflow_dispatch-only Jobs |");
  lines.push("| --- | --- | --- |");
  lines.push(...renderManualDispatchRows(config));
  lines.push("");
  lines.push("## Branch Protection Policy");
  lines.push("");
  lines.push(
    `- Default branch: \`${config.branch_protection.default_branch}\``,
  );
  lines.push(
    `- Allowed required aggregate checks: ${renderList(config.branch_protection.allowed_required_aggregates)}`,
  );
  lines.push(
    `- Dedicated audit workflow: \`${config.branch_protection.audit_workflow}\``,
  );
  lines.push("- Repo-side script exists at `scripts/ci/check-branch-protection.sh`; remote");
  lines.push("  enforcement must be validated in a privileged audit context.");
  lines.push("");
  lines.push("## Feature Flags");
  lines.push("");
  lines.push("| Feature | Status | Workflow | Job |");
  lines.push("| --- | --- | --- | --- |");
  lines.push(...renderFeatureRows(config));
  lines.push("");
  lines.push("## Required Job Mode");
  lines.push("");
  for (const [scope, mode] of Object.entries(config.policy_flags?.required_job_mode ?? {})) {
    lines.push(`- ${scope}: \`${mode}\``);
  }
  lines.push("");
  lines.push("## Allowed Informational Continue-on-error Steps");
  lines.push("");
  lines.push("| Workflow | Job | Step Names |");
  lines.push("| --- | --- | --- |");
  lines.push(...renderContinueOnErrorRows(config));
  lines.push("");
  lines.push("## Deterministic Core Entry Points");
  lines.push("");
  lines.push("| Scope | Script Entry Point |");
  lines.push("| --- | --- |");
  lines.push(...renderDeterministicCoreRows(config));
  lines.push("");
  lines.push("## Threshold Summary");
  lines.push("");
  lines.push("| Threshold Key | pr | nightly |");
  lines.push("| --- | --- | --- |");
  lines.push(...renderThresholdRows(thresholdsByProfile));
  lines.push("");
  return `${lines.join("\n")}\n`;
}

function main() {
  const options = parseArgs(process.argv.slice(2));
  const config = loadYaml(options.configPath);
  const rendered = renderDoc(config, options.configPath);

  if (options.stdout) {
    process.stdout.write(rendered);
    return;
  }

  if (options.check) {
    const current = readFileSync(resolve(options.outputPath), "utf8");
    if (current !== rendered) {
      process.exit(2);
    }
    return;
  }

  writeFileSync(resolve(options.outputPath), rendered, "utf8");
}

main();
