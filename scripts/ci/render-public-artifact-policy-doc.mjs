#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import YAML from "../lib/yaml-loader.mjs";

const repoRoot = process.cwd();
const configPath = resolve(repoRoot, "configs/governance/public-artifact-policy.yaml");
const outputPath = resolve(repoRoot, "docs/reference/public-artifact-policy.md");
const checkOnly = process.argv.includes("--check");

const config = YAML.parse(readFileSync(configPath, "utf8"));

function renderList(items) {
  if (!Array.isArray(items) || items.length === 0) {
    return ["- _none_"];
  }
  return items.map((item) => `- \`${item}\``);
}

const lines = [
  "# Reference: Public Artifact Policy",
  "",
  "Generated from `configs/governance/public-artifact-policy.yaml`. Do not edit this file manually.",
  "",
  "## Current Mode",
  "",
  "| Key | Value |",
  "| --- | --- |",
  `| current mode | \`${config.current_mode}\` |`,
  `| public workflow enabled | \`${String(config.public_workflow_enabled)}\` |`,
  `| default failure bundle mode | \`${config.default_failure_bundle_mode}\` |`,
  "",
  "## Policy Statement",
  "",
  `> ${config.policy_statement}`,
  "",
  "## Private-only Artifact Paths",
  "",
  ...renderList(config.private_only_paths),
  "",
  "## Public-safe Candidate Paths",
  "",
  ...renderList(config.public_safe_candidates),
  "",
  "## Enforcement Checks",
  "",
  ...renderList(config.enforcement_checks),
  "",
];

const rendered = `${lines.join("\n")}\n`;

if (checkOnly) {
  const current = readFileSync(outputPath, "utf8");
  if (current !== rendered) {
    console.error("[public-artifact-policy-render] FAIL docs/reference/public-artifact-policy.md is out of date");
    process.exit(1);
  }
  console.log("[public-artifact-policy-render] PASS");
  process.exit(0);
}

writeFileSync(outputPath, rendered, "utf8");
console.log(`[public-artifact-policy-render] WROTE ${outputPath}`);
