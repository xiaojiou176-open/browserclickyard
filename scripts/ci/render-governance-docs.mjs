function main() {
  const options = parseArgs(process.argv.slice(2));
  const selected = options.only
    ? SPEC.filter((item) => item.output === options.only || item.config === options.only)
    : SPEC;

  let failed = false;
  const renderedDocs = selected.map((item) => {
    const config = loadYaml(item.config);
    const output = item.render(config, item.config);
    return { ...item, outputText: output };
  });

  if (options.stdout) {
    for (const item of renderedDocs) {
      process.stdout.write(`=== ${item.output} ===\n${item.outputText}`);
    }
    return;
  }

  for (const item of renderedDocs) {
    if (options.check) {
      const current = readFileSync(resolve(item.output), "utf8");
      if (current !== item.outputText) {
        failed = true;
        console.error(`[render-governance-docs] stale render: ${item.output}`);
      }
      continue;
    }
    writeFileSync(resolve(item.output), item.outputText, "utf8");
  }

  if (failed) {
    process.exit(2);
  }
}

main();
