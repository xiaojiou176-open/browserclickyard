function renderUpstreamCustomizations(config, configPath) {
  const lines = renderDocHeader("Upstream Customizations", configPath);
  lines.push(
    "This page tracks repo-local customizations against third-party source registries. It does not represent Git fork drift or a canonical upstream branch audit.",
  );
  lines.push("");
  lines.push("| System | Local Path | What Changed | Why | Rollback Strategy |");
  lines.push("| --- | --- | --- | --- | --- |");
  let customizationCount = 0;
  for (const item of config.systems ?? []) {
    const customizations = Array.isArray(item.customizations) ? item.customizations : [];
    for (const customization of customizations) {
      customizationCount += 1;
      lines.push(
        `| \`${item.system_id}\` | \`${customization.local_path}\` | ${customization.what_changed} | ${customization.why} | ${customization.rollback_strategy} |`,
      );
    }
  }
  if (customizationCount === 0) {
    lines.push("| _none_ | _none_ | No active tracked customizations | _n/a_ | use upstream-inventory rollback strategy |");
  }
  lines.push("");
  return `${lines.join("\n")}\n`;
}

