function parseArgs(argv) {
  const options = {
    check: false,
    stdout: false,
    only: "",
  };
  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];
    const next = argv[index + 1];
    if (token === "--check") {
      options.check = true;
      continue;
    }
    if (token === "--stdout") {
      options.stdout = true;
      continue;
    }
    if (token === "--only" && next) {
      options.only = next.trim();
      index += 1;
    }
  }
  return options;
}

function loadYaml(filePath) {
  return YAML.parse(readFileSync(resolve(filePath), "utf8"));
}

function renderList(items) {
  if (!Array.isArray(items) || items.length === 0) {
    return "_none_";
  }
  return items.map((item) => `\`${item}\``).join(", ");
}

function renderDocHeader(title, configPath) {
  return [
    `# Reference: ${title}`,
    "",
    `Generated from \`${configPath}\`. Do not edit this file manually.`,
    "",
  ];
}

function renderRootGovernance(config, configPath) {
  const lines = renderDocHeader("Root Governance", configPath);
  lines.push("## Allowed Tracked Directories");
  lines.push("");
  lines.push("| Group | Entries |");
  lines.push("| --- | --- |");
  for (const [group, entries] of Object.entries(config?.tracked_root?.allowed_directories ?? {})) {
    lines.push(`| ${group} | ${renderList(entries)} |`);
  }
  lines.push("");
  lines.push("## Allowed Tracked Files");
  lines.push("");
  lines.push(renderList(config?.tracked_root?.allowed_files ?? []));
  lines.push("");
  lines.push("## Explicit Exceptions");
  lines.push("");
  lines.push("| Directory | Owner | Reason | Exit Criteria |");
  lines.push("| --- | --- | --- | --- |");
  for (const item of config?.tracked_root?.explicit_exceptions?.directories ?? []) {
    lines.push(
      `| \`${item.name}\` | \`${item.owner}\` | ${item.reason} | ${item.exit_criteria} |`,
    );
  }
  lines.push("");
  lines.push("## Disallowed Runtime Outputs");
  lines.push("");
  lines.push(renderList(config?.tracked_root?.disallowed_runtime_outputs ?? []));
  lines.push("");
  return `${lines.join("\n")}\n`;
}

